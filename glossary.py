def find_new_term(text, explained):
    """The first glossary term in this text that the video hasn't explained yet."""
    hits = []
    for entry in TERMS:
        if entry["term"] in explained:
            continue
        # all-capital terms must match exactly, so "fir" (phir) and "ai" stay ordinary words
        letters = re.sub(r"\\[bB]", "", entry["match"])
        flags = 0 if letters.isupper() or not any(c.islower() for c in letters) else re.I
        m = re.search(entry["match"], text, flags)
        if m:
            hits.append((m.start(), entry))
    return min(hits, key=lambda h: h[0])[1] if hits else None


def term_visual(entry):
    """The picture for an explanation: a pen diagram when there is one, otherwise a notebook card."""
    if entry.get("pen"):
        return {"type": "pen", "title": entry["term"], **entry["pen"]}
    return {"type": "term", "term": entry["term"], "meaning": entry["meaning"],
            "example": entry["example"], "icon": entry["icon"]}
